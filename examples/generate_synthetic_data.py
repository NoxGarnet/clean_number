"""Generate the small, non-experimental fixtures used by the public tests."""

from __future__ import annotations

from pathlib import Path


ROOT = Path(__file__).resolve().parent / "synthetic" / "input"


def write_table(path: Path, headers: list[str], rows: list[list[float]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["synthetic fixture; generated by generate_synthetic_data.py", "\t".join(headers)]
    lines.extend("\t".join(str(value) for value in row) for row in rows)
    path.write_text("\n".join(lines) + "\n", encoding="gbk")


def compression_rows(scale: float) -> list[list[float]]:
    return [[i * 0.1, i * 10.0 * scale, i * 10.0 * scale, i * 0.1] for i in range(7)]


def flexural_rows(scale: float) -> list[list[float]]:
    return [[i * 0.1, i * 10.0 * scale, i * 0.05, i * 0.1] for i in range(7)]


def main() -> None:
    compression = ROOT / "compression"
    flexural = ROOT / "flexural"
    for path in (compression, flexural):
        path.mkdir(parents=True, exist_ok=True)

    headers = ["时间 (s)", "力 (kN)", "应力 (MPa)", "应变 (%)"]
    for condition, scale in (("control", 1.0), ("treated", 1.2)):
        for end in (1, 2):
            write_table(
                compression / f"d28{condition}1-{end}.xls",
                headers,
                compression_rows(scale * (1.0 + 0.02 * (end - 1))),
            )

    flexural_headers = ["时间 (s)", "力 (kN)", "应力 (MPa)", "变形 (mm)"]
    for condition, scale in (("control", 1.0), ("treated", 1.2)):
        write_table(flexural / f"d28{condition}1.xls", flexural_headers, flexural_rows(scale))


if __name__ == "__main__":
    main()
